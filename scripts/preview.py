def _get_preview_js() -> str:
    """Generate JavaScript for the preview page."""
    return """
    // Add copy-to-clipboard functionality for SVG
    document.querySelectorAll('svg').forEach(svg => {
        svg.style.cursor = 'pointer';
        svg.title = 'Click to copy SVG';
        svg.addEventListener('click', () => {
            const serializer = new XMLSerializer();
            const svgString = serializer.serializeToString(svg);
            navigator.clipboard.writeText(svgString).then(() => {
                showToast('SVG copied to clipboard!');
            });
        });
    });

    function showToast(message) {
        const toast = document.createElement('div');
        toast.textContent = message;
        toast.style.cssText = 'position:fixed;bottom:2rem;left:50%;transform:translateX(-50%);background:#22c55e;color:white;padding:0.75rem 1.5rem;border-radius:8px;box-shadow:0 4px 24px rgba(0,0,0,0.3);z-index:1000;animation:slideUp 0.3s ease';
        document.body.appendChild(toast);
        setTimeout(() => {
            toast.style.animation = 'slideDown 0.3s ease';
            setTimeout(() => toast.remove(), 300);
        }, 2000);
    }

    // Add toast animations
    const style = document.createElement('style');
    style.textContent = '@keyframes slideUp{from{opacity:0;transform:translateX(-50%) translateY(20px)}to{opacity:1;transform:translateX(-50%) translateY(0)}}@keyframes slideDown{from{opacity:1;transform:translateX(-50%) translateY(0)}to{opacity:0;transform:translateX(-50%) translateY(20px)}}';
    document.head.appendChild(style);
    """


def _render_preview_section(title: str, svg_content: Optional[str], key: str) -> str:
    """Render a preview section with an SVG."""
    if not svg_content:
        return f"""
        <section class="section">
            <h2>{xml_escape(title)}</h2>
            <div class="preview-card" style="min-height: 200px; display: flex; align-items: center; justify-content: center; color: #888;">
                Not generated
            </div>
        </section>
        """
    return f"""
        <section class="section">
            <h2>{xml_escape(title)}</h2>
            <div class="preview-card">
                {svg_content}
            </div>
        </section>
        """


def _render_individual_cards(cards: Dict[str, str]) -> str:
    """Render individual stat cards."""
    if not cards:
        return '<p style="color: #888; text-align: center; grid-column: 1/-1;">Not generated</p>'

    items = []
    for key, svg in cards.items():
        label = key.replace("_", " ").title()
        items.append(f'''
        <div class="card-item" title="{xml_escape(label)}">
            {svg}
        </div>
        ''')
    return "\n".join(items)


def _render_wrapped_cards(cards: Dict[str, str]) -> str:
    """Render wrapped summary cards."""
    if not cards:
        return '<p style="color: #888; text-align: center; grid-column: 1/-1;">Not generated</p>'

    items = []
    for key, svg in cards.items():
        label = key.replace("_", " ").title()
        items.append(f'''
        <div class="card-item" title="{xml_escape(label)}">
            {svg}
        </div>
        ''')
    return "\n".join(items)


def write_preview_file(html: str, output_path: str) -> None:
    """Write the preview HTML to a file."""
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)


